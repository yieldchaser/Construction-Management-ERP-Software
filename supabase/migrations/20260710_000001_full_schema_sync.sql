-- ============================================================================
-- 20260710_000001_full_schema_sync.sql
-- Full schema sync: backend/app/models.py (SQLAlchemy) -> Supabase Postgres
-- ============================================================================
--
-- WHY THIS FILE EXISTS
-- ---------------------------------------------------------------------------
-- The 4 prior migrations in this folder (20260707_000001_library_columns.sql,
-- 20260709_000001_project_tab_foundation.sql,
-- 20260709_000002_transaction_task_columns.sql,
-- 20260709_000003_finance_tab_columns.sql) are all ALTER TABLE ... ADD COLUMN
-- deltas against tables that are assumed to already exist (companies,
-- projects, bills, tasks, library_parties, library_cost_codes,
-- library_materials, bank_accounts, payment_requests), plus a handful of
-- CREATE TABLE IF NOT EXISTS statements for 8 new tables introduced by the
-- Project Tab Parity build (project_members, project_locations,
-- project_parties, library_retentions, transaction_retentions,
-- material_categories, todos, todo_assignees). Nowhere in supabase/migrations
-- is there a migration that actually CREATEs the ~120 other base tables
-- (companies, users, projects, tasks, bills, purchase_orders,
-- staff_employees, library_parties, ... every table in models.py). Running
-- migrations 1-4 in order against a genuinely empty Postgres database would
-- fail immediately (e.g. migration 2's `CREATE TABLE project_parties (...
-- REFERENCES library_parties(id) ...)` errors because `library_parties` does
-- not exist yet). The only place the full current schema has ever been
-- materialized is via SQLAlchemy's `Base.metadata.create_all(bind=engine)`
-- call in backend/app/main.py (line 19), which runs unconditionally for any
-- engine (SQLite *and* Postgres) and silently no-ops for tables that already
-- exist -- it does NOT add missing columns to a table that already exists
-- with an older, incomplete column set (that gap is exactly what
-- `ensure_sqlite_schema_sync()` back-fills for SQLite dev, and what this
-- migration back-fills for Postgres/Supabase).
--
-- Conclusion for task item 7: a full base schema WAS needed, not just
-- incremental deltas. This migration is therefore self-sufficient: it can be
-- applied to a completely empty Supabase project on its own, AND it is safe
-- to apply on top of an environment where the 4 prior migrations (or an
-- earlier partial `create_all()` bootstrap) already ran, because every
-- statement is defensive/idempotent (`CREATE TABLE IF NOT EXISTS`,
-- `ADD COLUMN IF NOT EXISTS`, and a small idempotent-FK helper for
-- `ADD CONSTRAINT`, since Postgres has no native
-- `ADD CONSTRAINT IF NOT EXISTS`).
--
-- SCOPE
-- ---------------------------------------------------------------------------
-- Covers all 128 tables currently declared in backend/app/models.py (every
-- `class ... (Base): __tablename__ = ...`), with every column, type,
-- nullability, default, primary key, unique constraint, index, and foreign
-- key exactly as declared there as of 2026-07-10. Generated by importing the
-- live `models.py` under a Postgres-drivername engine (so the file's own
-- SQLite-vs-Postgres branching -- see `SQLiteUUID` / `JSONB` near the top of
-- models.py -- resolves to the real `postgresql.UUID` / `postgresql.JSONB`
-- types) and compiling each table via SQLAlchemy's own Postgres DDL compiler,
-- then augmenting the output with server-side DEFAULTs, indexes and foreign
-- keys to match the conventions already established in the 4 prior
-- hand-written migrations. This removes hand-transcription risk across ~1400
-- columns while keeping the output plain, readable SQL.
--
-- STRUCTURE
-- ---------------------------------------------------------------------------
--   PART 1  CREATE TABLE IF NOT EXISTS for all 128 tables (columns, PKs,
--           single-column UNIQUE constraints only -- models.py defines no
--           composite UniqueConstraint/Index/__table_args__ anywhere).
--   PART 2  ALTER TABLE ... ADD COLUMN IF NOT EXISTS for every column of
--           every table, defensively, in case a table already exists (from
--           the 4 prior migrations, or an earlier partial `create_all()`
--           run against Postgres) but is missing columns added later in
--           models.py's history.
--   PART 3  Foreign keys, added idempotently via a small helper function
--           (`_sf_add_fk_if_not_exists`) that checks pg_constraint before
--           adding, since CREATE TABLE in PART 1 intentionally omits inline
--           FK clauses (this lets PART 1 run in any order without having to
--           hand-solve the ~128-table dependency graph, and lets FKs be
--           back-filled onto tables that pre-existed without them). The
--           helper function is dropped again at the end of PART 3.
--   PART 4  CREATE INDEX IF NOT EXISTS for columns declared `index=True` in
--           models.py that are not already covered by a PRIMARY KEY/UNIQUE
--           (companies.parent_company_id, delete_logs.company_id,
--           moms.company_id, moms.project_id). companies.slug is
--           `unique=True, index=True` together, which SQLAlchemy/Postgres
--           satisfy with a single UNIQUE constraint (already in PART 1), so
--           it is intentionally not duplicated here.
--
-- TYPE-MAPPING / DIALECT ASSUMPTIONS (per task item 6 and the "do not guess"
-- instruction -- noted explicitly since Postgres and SQLite diverge here)
-- ---------------------------------------------------------------------------
--  * UUID columns -> native Postgres `uuid`, matching models.py's
--    non-SQLite branch (`from sqlalchemy.dialects.postgresql import UUID`).
--    Primary-key UUID defaults use `gen_random_uuid()` (pgcrypto), the same
--    function already relied upon by migration
--    20260709_000001_project_tab_foundation.sql, so `pgcrypto` is enabled
--    below defensively via `CREATE EXTENSION IF NOT EXISTS`.
--  * JSON columns -> native Postgres `jsonb`, matching models.py's
--    non-SQLite branch (`from sqlalchemy.dialects.postgresql import JSONB`).
--    Columns whose Python-side default is `list` get a server-side
--    `DEFAULT '[]'::jsonb`; nullable JSON columns with no Python default
--    (e.g. chat_messages.image_urls) are left with no server default.
--  * SQLAlchemy `Float` columns -> `double precision` (not bare `FLOAT`) to
--    match the exact spelling already used for the same columns in
--    20260709_000003_finance_tab_columns.sql (functionally identical types
--    in Postgres; this is a spelling/style normalization only).
--  * Bare/unbounded `String`/`Text` columns (no length argument) -> `text`,
--    matching the convention already used across all 4 prior migrations for
--    the equivalent columns, rather than emitting an unbounded `varchar`
--    (functionally near-identical in Postgres; `text` is the idiomatic
--    choice and what models.py's own comments describe, e.g. Project.location
--    "mapping as String for basic schema").
--  * `DateTime(timezone=True)` -> `timestamp with time zone`; plain `Date`
--    (CRMQuotation.qt_date) -> `date`; `LargeBinary` -> `bytea`;
--    `BigInteger` -> `bigint`.
--  * `Boolean` columns with the legacy SQLite-style `server_default="0"`
--    sentinel (Company.negative_stock_lock and 8 sibling flags,
--    CompanyBranch.is_primary, CustomField.set_default) are normalized to
--    canonical Postgres boolean literals: `DEFAULT false`. `DEFAULT '0'`
--    is technically also valid Postgres boolean-literal syntax, but `false`
--    is the unambiguous, idiomatic form and matches
--    20260709_000001_project_tab_foundation.sql's `is_pinned ... DEFAULT
--    false`.
--  * `created_at`/`updated_at` columns declared with a Python-side
--    `default=func.now()` (client-side only in SQLAlchemy -- it does not by
--    itself produce a DDL-level DEFAULT) are given an explicit
--    `DEFAULT now()` here, matching the same choice already made in all 4
--    prior migrations, so the schema is self-sufficient for inserts issued
--    outside the SQLAlchemy ORM. Columns using `onupdate=func.now()`
--    (e.g. Project.updated_at) are NOT given a Postgres trigger to
--    auto-refresh on UPDATE -- that behavior is enforced at the SQLAlchemy
--    ORM layer only, consistent with the fact that none of the 4 prior
--    migrations add such a trigger either.
--  * PART 2's defensive `ADD COLUMN IF NOT EXISTS` statements only assert
--    `NOT NULL` when a matching `DEFAULT` is also present (safe to backfill
--    existing rows in a table that already has data). Columns that are
--    `nullable=False` in models.py but have no Python/server default at all
--    (e.g. a handful of true "always supplied by the app" foreign keys) are
--    added as nullable in PART 2 to avoid ALTER TABLE failures against a
--    table that already has rows; PART 1's CREATE TABLE (fresh tables only,
--    never pre-populated) enforces the full NOT NULL exactly as declared in
--    models.py. This is an intentionally conservative choice given the task
--    is explicitly targeting an "empty or near-empty" database, not a
--    guarantee that every legacy row in a hypothetical partially-migrated
--    table would already satisfy a brand-new NOT NULL constraint.
--
-- Extensions ------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pgcrypto;

