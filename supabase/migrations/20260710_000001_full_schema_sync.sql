CREATE OR REPLACE FUNCTION _sf_add_fk_if_not_exists(
  p_table text, p_constraint_name text, p_definition text
) RETURNS void AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    WHERE c.conname = p_constraint_name AND t.relname = p_table
  ) THEN
    EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s', p_table, p_constraint_name, p_definition);
  END IF;
END;
$$ LANGUAGE plpgsql;

